// Copies the feedback widget loader's texts (keys fbw.l.*) from the
// translation tables into src/widget/strings.ts, so the loader stays small.
// Run: bun scripts/widget-strings.ts (a test checks that it is up to date).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function widgetStrings(root: string) {
  const out: Record<string, Record<string, string>> = {};
  for (const l of ["en", "de"]) {
    const ts = readFileSync(join(root, "src", "i18n", `${l}.ts`), "utf8");
    out[l] = {};
    for (const m of ts.matchAll(/^\s*"(fbw\.l\.[^"]+)":\s*("(?:[^"\\]|\\.)*"),?\s*$/gm)) out[l][m[1]] = JSON.parse(m[2]);
  }
  return `// Generated by scripts/widget-strings.ts from src/i18n – do not edit.\nexport const strings = ${JSON.stringify(out, null, 2)} as const;\n`;
}

if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  writeFileSync(join(root, "src", "widget", "strings.ts"), widgetStrings(root));
}
