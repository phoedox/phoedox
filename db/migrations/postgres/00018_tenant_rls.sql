-- +goose Up
-- Row-level security for the hosted variant: every table is filtered by
-- tenant_id = current_setting('phoedox.tenant'). The server sets the value
-- per connection (single tenant: 'default' at connect; multi-tenant: per
-- statement from the request's host). '*' is used only by system work
-- (migrations, background jobs, housekeeping). Superusers and roles with
-- BYPASSRLS are not filtered, so the hosted server refuses to run as one.
-- Data migrations from here on must start with
--   SELECT set_config('phoedox.tenant', '*', true);
CREATE TABLE tenant_domains (
  domain     TEXT PRIMARY KEY,
  tenant_id  TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

